export function getAllWords(): { word: string; category: Category }[] {
  return categories.flatMap((cat) =>
    cat.words.map((word) => ({ word, category: cat }))
  );
}

export function getRandomWordFromCategories(selectedIds: string[]): {
  word: string;
  category: Category;
} {
  const pool = categories
    .filter((c) => selectedIds.includes(c.id))
    .flatMap((cat) => cat.words.map((word) => ({ word, category: cat })));

  if (pool.length === 0) {
    const fallback = categories[0];
    const word = fallback.words[Math.floor(Math.random() * fallback.words.length)];
    return { word, category: fallback };
  }

  return pool[Math.floor(Math.random() * pool.length)];
}
