export const CATEGORY_KEYS = Object.keys(CATEGORIES)

/**
 * Pick a random category and word, ensuring they differ from the last round.
 * @param {string} [lastCategory] - category key used in the previous round
 * @param {string} [lastWord] - word used in the previous round
 */
export function pickRandomRound(lastCategory = null, lastWord = null) {
  let categoryKey
  let word

  // Try up to 10 times to avoid repeating the same category
  for (let i = 0; i < 10; i++) {
    const keys = CATEGORY_KEYS
    categoryKey = keys[Math.floor(Math.random() * keys.length)]
    if (lastCategory && categoryKey === lastCategory && CATEGORY_KEYS.length > 1) {
      continue
    }
    const words = CATEGORIES[categoryKey].words
    word = words[Math.floor(Math.random() * words.length)]
    if (lastWord && word === lastWord) continue
    break
  }

  return {
    categoryKey,
    category: CATEGORIES[categoryKey].label,
    categoryEmoji: CATEGORIES[categoryKey].emoji,
    word,
  }
}
